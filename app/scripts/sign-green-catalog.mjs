import { createHash, createPrivateKey, createPublicKey, generateKeyPairSync, sign, verify } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const catalogPath = resolve(root, "public/catalog/green-pilot.v1.json")
const outputPath = resolve(root, "src/lib/catalog/catalog-signature.ts")
const publicSignaturePath = resolve(root, "public/catalog/green-pilot.v1.sig.json")
const catalog = JSON.parse(readFileSync(catalogPath, "utf8"))
const payload = Buffer.from(JSON.stringify(catalog))

let privateKey
if (process.env.GREEN_CATALOG_PRIVATE_KEY) {
  privateKey = createPrivateKey(process.env.GREEN_CATALOG_PRIVATE_KEY.replaceAll("\\n", "\n"))
} else {
  privateKey = generateKeyPairSync("ed25519").privateKey
  process.stderr.write("Generated an ephemeral Ed25519 catalog key. Rotate by re-signing the next version.\n")
}

const publicKey = createPublicKey(privateKey)
const signature = sign(null, payload, privateKey)
if (!verify(null, payload, publicKey, signature)) throw new Error("Catalog signature self-check failed")

const publicPem = publicKey.export({ type: "spki", format: "pem" }).toString()
const source = `// Generated by scripts/sign-green-catalog.mjs. Never commit a private key.\nexport const GREEN_CATALOG_PUBLIC_KEY = ${JSON.stringify(publicPem)} as const\nexport const GREEN_CATALOG_SIGNATURE = ${JSON.stringify(signature.toString("base64"))} as const\n`
writeFileSync(outputPath, source)
writeFileSync(publicSignaturePath, `${JSON.stringify({ algorithm: "Ed25519", catalogVersion: catalog.catalogVersion, digest: createHash("sha256").update(payload).digest("hex"), publicKey: publicPem, signature: signature.toString("base64") }, null, 2)}\n`)
process.stdout.write(`Signed ${catalog.tracks.length} tracks for catalog ${catalog.catalogVersion}.\n`)
